module.exports = (sequelize, DataTypes) => {
  const Question = sequelize.define('Question', {
    id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true },
    stable_id: { type: DataTypes.STRING(36), allowNull: false, unique: { msg: 'Stable ID already exists' } },
    pdf_document_id: { type: DataTypes.INTEGER, allowNull: true },
    page_number: { type: DataTypes.INTEGER, allowNull: true },
    subject_id: { type: DataTypes.INTEGER, allowNull: false },
    chapter_id: { type: DataTypes.INTEGER, allowNull: true },
    ilearn_chapter_id: { type: DataTypes.INTEGER, allowNull: true },
    exam_year: { type: DataTypes.INTEGER, allowNull: true },
    exam_type: { type: DataTypes.STRING(50), allowNull: true },
    source: { type: DataTypes.STRING(255), allowNull: true },
    question_number: { type: DataTypes.STRING(50), allowNull: false },
    question_text: { type: DataTypes.TEXT, allowNull: false },
    option_a: { type: DataTypes.TEXT, allowNull: true },
    option_b: { type: DataTypes.TEXT, allowNull: true },
    option_c: { type: DataTypes.TEXT, allowNull: true },
    option_d: { type: DataTypes.TEXT, allowNull: true },
    options_json: { type: DataTypes.JSON, allowNull: true },
    original_answer_key: { type: DataTypes.STRING(10), allowNull: true },
    original_explanation: { type: DataTypes.TEXT, allowNull: true },
    verified_answer_key: { type: DataTypes.STRING(10), allowNull: true },
    suggested_explanation: { type: DataTypes.TEXT, allowNull: true },
    approved_answer_key: { type: DataTypes.STRING(10), allowNull: true },
    approved_explanation: { type: DataTypes.TEXT, allowNull: true },
    ai_confidence: { type: DataTypes.FLOAT, allowNull: true },
    needs_human_review: { type: DataTypes.BOOLEAN, defaultValue: true },
    review_status: {
      type: DataTypes.ENUM('pending', 'approved', 'rejected', 'edited', 'unresolved'),
      defaultValue: 'pending',
    },
    extraction_method: { type: DataTypes.ENUM('text', 'ocr', 'hybrid'), defaultValue: 'text' },
    ocr_confidence: { type: DataTypes.FLOAT, allowNull: true },
    extraction_warnings: { type: DataTypes.TEXT, allowNull: true },
    extraction_flags: { type: DataTypes.JSON, allowNull: true },
    metadata: { type: DataTypes.JSON, allowNull: true },
    created_at: { type: DataTypes.DATE, defaultValue: new Date() },
  }, {
    tableName: 'questions',
    indexes: [
      { fields: ['stable_id'], unique: true },
      { fields: ['pdf_document_id'] },
      { fields: ['subject_id'] },
      { fields: ['chapter_id'] },
      { fields: ['exam_year'] },
      { fields: ['review_status'] },
      { fields: ['needs_human_review'] },
      { fields: ['extraction_method'] },
      { fields: ['created_at'] },
      { fields: ['subject_id', 'chapter_id', 'exam_year'] },
    ],
  });

  return Question;
};
